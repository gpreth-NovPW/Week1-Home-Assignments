function isOddOrEven() {
    let num = 34;
    if (num % 2 === 0) {
        console.log("Even number");
    } else {
        console.log("Odd number");
    }
}
isOddOrEven(); // Even number


function isOddOrEven() {
    let num = 12;
    if (num % 2 != 0) {
        console.log("Even number");
    } else {
        console.log("Odd number");
    }
}
isOddOrEven(); // Odd number